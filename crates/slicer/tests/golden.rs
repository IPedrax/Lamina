//! Golden G-code: small models whose G-code is checked line by line, so any change to the slicer shows up as a diff that is either
//! a fix or a regression. Each case in `tests/golden/` is a mesh (`NAME.stl`, put in the middle of the plate) or a project
//! (`NAME.lamina`, with its objects where they stand), an optional `NAME.json` of profile fields, and the expected `NAME.gcode`.
//!
//! `LAMINA_BLESS=1 cargo test -p lamina-slicer --test golden` writes what the slicer makes now over the expected files, to be read
//! in the diff before it is committed.
//!
//! Numbers are compared to a little under the precision they are written at (X, Y and Z to 0.002 mm, E to 0.0002 mm), because the
//! three systems CI runs on may round a sine differently in its last bit; everything else must match exactly.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::{Path, PathBuf};

use lamina_core::Session;
use serde_json::{Value, json};

fn dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests").join("golden")
}

/// The G-code the slicer makes for the case at `input`.
fn slice(input: &Path) -> String {
    let mut s = Session::new();
    s.register(lamina_slicer::COMMANDS);
    let path = input.to_string_lossy().into_owned();
    let loaded = if input.extension().is_some_and(|e| e == "lamina") {
        s.execute("open", &json!({"path": path}))
    } else {
        s.execute("import_mesh", &json!({"path": path}))
    };
    loaded.unwrap_or_else(|e| panic!("{path}: {e}"));
    let profile: Value = std::fs::read_to_string(input.with_extension("json"))
        .map(|t| serde_json::from_str(&t).unwrap_or_else(|e| panic!("{}: {e}", input.with_extension("json").display())))
        .unwrap_or(json!({}));
    let out =
        std::env::temp_dir().join(format!("lamina-golden-{}-{}.gcode", input.file_stem().unwrap().to_string_lossy(), std::process::id()));
    s.execute("slice", &json!({"path": out, "profile": profile})).unwrap_or_else(|e| panic!("{path}: {e}"));
    let g = std::fs::read_to_string(&out).unwrap();
    std::fs::remove_file(&out).unwrap();
    normal(&g)
}

/// The text with Unix line ends and without the line naming the version that wrote it.
fn normal(g: &str) -> String {
    g.replace("\r\n", "\n").lines().filter(|l| !l.starts_with("; generated by")).map(|l| format!("{l}\n")).collect()
}

/// Whether two words of G-code say the same thing: equal, or the same axis with numbers within what rounding can change.
fn same_word(a: &str, b: &str) -> bool {
    if a == b {
        return true;
    }
    let (Some(x), Some(y)) = (a.chars().next(), b.chars().next()) else { return false };
    let tolerance = match x {
        'X' | 'Y' | 'Z' => 0.002,
        'E' => 0.0002,
        _ => return false,
    };
    let (Ok(p), Ok(q)) = (a[1..].parse::<f64>(), b[1..].parse::<f64>()) else { return false };
    x == y && (p - q).abs() <= tolerance
}

/// The first line where `got` differs from `want`, with its number.
fn first_difference(got: &str, want: &str) -> Option<(usize, String, String)> {
    let (g, w): (Vec<&str>, Vec<&str>) = (got.lines().collect(), want.lines().collect());
    for k in 0..g.len().max(w.len()) {
        let (a, b) = (g.get(k).copied().unwrap_or("<end of file>"), w.get(k).copied().unwrap_or("<end of file>"));
        let (wa, wb): (Vec<&str>, Vec<&str>) = (a.split_whitespace().collect(), b.split_whitespace().collect());
        if wa.len() != wb.len() || !wa.iter().zip(&wb).all(|(x, y)| same_word(x, y)) {
            return Some((k + 1, a.to_string(), b.to_string()));
        }
    }
    None
}

#[test]
fn every_golden_model_slices_to_its_expected_gcode() {
    let bless = std::env::var("LAMINA_BLESS").is_ok_and(|v| v == "1");
    let mut cases: Vec<PathBuf> = std::fs::read_dir(dir())
        .unwrap()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "stl" || e == "lamina"))
        .collect();
    cases.sort();
    assert!(cases.len() >= 4, "the golden models are missing: {cases:?}");
    let mut failed = Vec::new();
    for input in &cases {
        let got = slice(input);
        let expected = input.with_extension("gcode");
        if bless {
            std::fs::write(&expected, &got).unwrap();
            continue;
        }
        let want = normal(&std::fs::read_to_string(&expected).unwrap_or_default());
        if let Some((line, g, w)) = first_difference(&got, &want) {
            failed.push(format!(
                "{}: line {line}\n  now:      {g}\n  expected: {w}\n  ({} lines now, {} expected)",
                expected.display(),
                got.lines().count(),
                want.lines().count()
            ));
        }
    }
    assert!(
        failed.is_empty(),
        "the G-code changed. If the change is meant, run `LAMINA_BLESS=1 cargo test -p lamina-slicer --test golden` and read the \
         diff before committing it.\n{}",
        failed.join("\n")
    );
}

#[test]
fn the_comparison_allows_rounding_and_nothing_else() {
    assert!(same_word("X10.001", "X10.002") && same_word("E0.03301", "E0.03310"));
    assert!(!same_word("X10.001", "Y10.001") && !same_word("X10.001", "X10.010") && !same_word("G1", "G0"));
    assert!(!same_word("F1200", "F1201"), "speeds match exactly");
    assert_eq!(first_difference("G1 X1.000\nM84\n", "G1 X1.001\nM84\n"), None);
    assert_eq!(first_difference("G1 X1.000\n", "G1 X1.000\nM84\n").map(|d| d.0), Some(2));
    assert_eq!(normal("; generated by Lamina 9.9\r\nG28\r\n"), "G28\n");
}
